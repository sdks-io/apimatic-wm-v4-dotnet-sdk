public sealed class WalmartApIsClient
{
    private readonly RawClient _rawClient;
    private readonly Server _server;
    private readonly AuthSchemes _auth;

    public WalmartApIsClient(HttpClient httpClient, WalmartApIsClientOptions options)
    {
        _server = new Server(options.Environment, options.Server);
        var queryParameterFactory = new QueryParameterFactory([]);
        var templateParamsFactory = new TemplateParamsFactory([]);
        var urlFactory = new UriFactory(queryParameterFactory, templateParamsFactory);
        var httpStatusPolicy = new HttpStatusPolicy([]);
        var headersFactory = new HeadersFactory([
            new HeaderParam("User-Agent", "WalmartApIsClient/1.0 CSharp"),
            new HeaderParam("X-APIMatic-Lang", "CSharp"),
            new HeaderParam("X-APIMatic-Package-Version", "1.0"),
            new HeaderParam("X-APIMatic-Gen-Version", "4.0.0"),
            new HeaderParam("X-APIMatic-OS", RuntimeEnvironment.Os),
            new HeaderParam("X-APIMatic-Runtime", RuntimeEnvironment.Runtime),
        ]);
        var resiliencePipelineFactory = new ResiliencePipelineFactory(options.Retry, options.TimeProvider);
        var httpLogger = new HttpLogger(options.Logging, "WalmartApIsClient", options.TimeProvider);
        var responseContexts = new ResponseContextFactory(options.TimeProvider, options.StreamReadTimeout);
        _rawClient =
            new RawClient(
                httpClient,
                urlFactory,
                httpStatusPolicy,
                headersFactory,
                resiliencePipelineFactory,
                httpLogger,
                options.Hooks,
                responseContexts);
        _auth = new AuthSchemes(options);
    }

    public AssortmentRecommendations AssortmentRecommendations =>
        field ??= new AssortmentRecommendations(_rawClient, _server);

    public Authorization Authorization => field ??= new Authorization(_rawClient, _server, _auth);

    public Disputes Disputes => field ??= new Disputes(_rawClient, _server);

    public FeedsApi FeedsApi => field ??= new FeedsApi(_rawClient, _server, _auth);

    public InsightApi InsightApi => field ??= new InsightApi(_rawClient, _server, _auth);

    public InventoryApi InventoryApi => field ??= new InventoryApi(_rawClient, _server, _auth);

    public LagTimeApi LagTimeApi => field ??= new LagTimeApi(_rawClient, _server, _auth);

    public Notifications Notifications => field ??= new Notifications(_rawClient, _server, _auth);

    public OnRequestReport OnRequestReport => field ??= new OnRequestReport(_rawClient, _server, _auth);

    public OnRequestReportApi OnRequestReportApi => field ??= new OnRequestReportApi(_rawClient, _server, _auth);

    public Prices Prices => field ??= new Prices(_rawClient, _server, _auth);

    public Promotions Promotions => field ??= new Promotions(_rawClient, _server);

