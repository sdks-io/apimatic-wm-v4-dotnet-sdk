using System.Text.Json.Serialization;
using WalmartApIs.Core.Models;
using WalmartApIs.Core.Validation;
using WalmartApIs.Core.Validation.Attributes;

namespace WalmartApIs.Models;

/// <summary>
/// RFC 9457 problem details for HTTP APIs (https://www.rfc-editor.org/rfc/rfc9457). Used for all 4xx and 5xx error responses in the Rich media management API.
/// </summary>
public record ProblemDetailsError1
{
    /// <summary>
    /// A URI reference that identifies the problem type. Dereferencing this URI should provide human-readable documentation.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("type")]
    [Format(FormatKind.Uri)]
    public string? Type { get; init; }

    /// <summary>
    /// A short, human-readable summary of the problem type. Should not change from occurrence to occurrence.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("title")]
    public string? Title { get; init; }

    /// <summary>
    /// The HTTP status code generated by the origin server for this occurrence of the problem.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("status")]
    public int? Status { get; init; }

    /// <summary>
    /// A human-readable explanation specific to this occurrence of the problem.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("detail")]
    public string? Detail { get; init; }

    /// <summary>
    /// A URI reference that identifies the specific occurrence of the problem. May be relative.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("instance")]
    [Format(FormatKind.UriReference)]
    public string? Instance { get; init; }

    /// <summary>
    /// Walmart rich media-specific error code. Pattern: RM-XXXX (e.g. RM-4001 for missing param, RM-4002 for invalid value).
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("code")]
    public string? Code { get; init; }

    [JsonExtensionData]
    public AdditionalProperties AdditionalProperties { get; init; } = [];
}
