using System.Text.Json.Serialization;
using WalmartApIs.Core.Models;
using WalmartApIs.Models.Enums;

namespace WalmartApIs.Models;

/// <summary>
/// The ingestion status of an individual item.
/// </summary>
public record ItemIngestionStatus
{
    /// <summary>
    /// Mart ID that a user or seller uses for a marketplace.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("martId")]
    public int? MartId { get; init; }

    /// <summary>
    /// An arbitrary alphanumeric unique ID, seller-specified, identifying each item.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("sku")]
    public string? Sku { get; init; }

    /// <summary>
    /// An alphanumeric product ID, generated by Walmart.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("wpid")]
    public string? Wpid { get; init; }

    /// <summary>
    /// index of items in the feed.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("index")]
    public int? Index { get; init; }

    /// <summary>
    /// Can be one of the following: DATA_ERROR, SYSTEM_ERROR, TIMEOUT_ERROR, or INPROGRESS
    /// </summary>
    [JsonPropertyName("ingestionStatus")]
    public required IngestionStatus IngestionStatus { get; init; }

    /// <summary>
    /// If the item is undergoing a compliance review, provides details about the review status, editing restrictions, and expected review timeframe.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("pendingStatusDescription")]
    public string? PendingStatusDescription { get; init; }

    /// <summary>
    /// List of errors for an item.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("ingestionErrors")]
    public IngestionErrors? IngestionErrors { get; init; }

    [JsonExtensionData]
    public AdditionalProperties AdditionalProperties { get; init; } = [];
}
