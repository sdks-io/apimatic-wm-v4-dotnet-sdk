using System.Text.Json.Serialization;
using WalmartApIs.Core.Models;

namespace WalmartApIs.Models;

public record GetUnpublishedItemsPayload
{
    /// <summary>
    /// The GTIN-compatible Product ID (i.e. UPC or EAN)
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("gtin")]
    public string? Gtin { get; init; }

    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("marketPrice")]
    public Price2? MarketPrice { get; init; }

    /// <summary>
    /// The Date when item becomes available to sell in Walmart
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("offerStartDate")]
    public string? OfferStartDate { get; init; }

    /// <summary>
    /// If item is trending in walmart
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("marketTrending")]
    public string? MarketTrending { get; init; }

    /// <summary>
    /// The lifecycle status of an item describes where the item listing is in the overall lifecycle
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("lifecycleStatus")]
    public string? LifecycleStatus { get; init; }

    /// <summary>
    /// It outlines the reason for an item when unpublished
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("unpublishReasons")]
    public string? UnpublishReasons { get; init; }

    /// <summary>
    /// Percentage of number of items that are converted into sales
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("conversionRate")]
    public int? ConversionRate { get; init; }

    /// <summary>
    /// A seller-specified, alphanumeric string uniquely identifying the product name
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("productName")]
    public string? ProductName { get; init; }

    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("gmvAmount")]
    public GmvAmount? GmvAmount { get; init; }

    /// <summary>
    /// Specifies the item identifier generated by Walmart
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("itemId")]
    public string? ItemId { get; init; }

    /// <summary>
    /// An average rating number for the item from customers
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("customerRating")]
    public string? CustomerRating { get; init; }

    /// <summary>
    /// number of times this item is viewed by customers
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("pageViews")]
    public int? PageViews { get; init; }

    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("price")]
    public Price2? Price { get; init; }

    /// <summary>
    /// The Date item becomes to Unpublished
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("unpublishedDate")]
    public string? UnpublishedDate { get; init; }

    /// <summary>
    /// Specifies the item brand
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("brand")]
    public string? Brand { get; init; }

    /// <summary>
    /// String of letters and/or numbers a partner uses to identify the item
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("sku")]
    public string? Sku { get; init; }

    /// <summary>
    /// Information about the condition of the product
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("condition")]
    public string? Condition { get; init; }

    /// <summary>
    /// A seller-specified, alphanumeric string uniquely identifying the Product Type
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("productType")]
    public string? ProductType { get; init; }

    /// <summary>
    /// The Date when item becomes unavailable to sell in Walmart
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("offerEndDate")]
    public string? OfferEndDate { get; init; }

    /// <summary>
    /// The status of an item when the item is in the submission process
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("publishStatus")]
    public string? PublishStatus { get; init; }

    /// <summary>
    /// Indicates whether the item is identified as a customer favorite based on customer demand.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("isCustomerFavorite")]
    public bool? IsCustomerFavorite { get; init; }

    [JsonExtensionData]
    public AdditionalProperties AdditionalProperties { get; init; } = [];
}
