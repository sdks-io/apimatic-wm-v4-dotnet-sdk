using System.Text.Json.Serialization;
using WalmartApIs.Core.Models;

namespace WalmartApIs.Models;

public record Insight1
{
    /// <summary>
    /// The sales lift we predict you’ll see after your recommended items are converted, sent to WFS and made available to sell.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("estimatedSalesLift")]
    public double? EstimatedSalesLift { get; init; }

    /// <summary>
    /// The number of units Walmart suggests you send to WFS based on the item's forecasted sales demand. These suggestions are generated by algorithms considering several factors including past sales, seasonality, listing, quality, pricing, and more.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("suggestedUnits")]
    public double? SuggestedUnits { get; init; }

    /// <summary>
    /// Indicates whether the item is identified as a customer favorite based on customer demand.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("customerFavorite")]
    public bool? CustomerFavorite { get; init; }

    [JsonExtensionData]
    public AdditionalProperties AdditionalProperties { get; init; } = [];
}
