using System;
using System.Text.Json.Serialization;
using WalmartApIs.Core.Models;
using WalmartApIs.Models.Enums;

namespace WalmartApIs.Models;

public record DownloadReportResponse
{
    /// <summary>
    /// URL to be used to download the report.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("downloadURL")]
    public string? DownloadUrl { get; init; }

    /// <summary>
    /// Time till when the URL to download the report will be valid.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("downloadURLExpirationTime")]
    public string? DownloadUrlExpirationTime { get; init; }

    /// <summary>
    /// Automated ID generated by system that uniquely identifies the report request.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("requestId")]
    public Guid? RequestId { get; init; }

    /// <summary>
    /// Status of report request. Possible values are RECEIVED, INPROGRESS, READY, ERROR.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("requestStatus")]
    public RequestStatus? RequestStatus { get; init; }

    /// <summary>
    /// Date and time on which the report request is submitted.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("requestSubmissionDate")]
    public string? RequestSubmissionDate { get; init; }

    /// <summary>
    /// Type of report for which the request is created. Example, ITEM for Item Report.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("reportType")]
    public ReportType? ReportType { get; init; }

    /// <summary>
    /// Version of report for which the request is created. Example, v1.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("reportVersion")]
    public string? ReportVersion { get; init; }

    /// <summary>
    /// Date and time on which the report is generated. Attribute is available only if report is generated.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("reportGenerationDate")]
    public string? ReportGenerationDate { get; init; }

    [JsonExtensionData]
    public AdditionalProperties AdditionalProperties { get; init; } = [];
}
